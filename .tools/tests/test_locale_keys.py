"""Exercise the official extractor in disposable trees, including failure cleanup."""
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
BASH = str(Path('C:/Program Files/Git/bin/bash.exe')) if os.name == 'nt' else shutil.which('bash')


@unittest.skipUnless(BASH and Path(BASH).is_file(), 'Bash is required')
class LocaleKeys(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='eui-locales-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / '.tools').mkdir()
        (self.root / 'EllesmereUILocales').mkdir()
        self.tmp = self.root / 'temp'
        self.tmp.mkdir()
        self.bin = self.root / 'bin'
        self.bin.mkdir()
        self.script = self.root / '.tools/extract-locale-keys.sh'
        self.script.write_bytes((ROOT / '.tools/extract-locale-keys.sh').read_bytes())
        self.output = self.root / 'EllesmereUILocales/_keys.txt'
        self.put('Core.lua', 'EllesmereUI.L("Zebra")\nEllesmereUI.Lf("Apple")\nEllesmereUI.L("Apple")\n')

    def put(self, name, data):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data, encoding='utf-8', newline='\n')

    def run_script(self, *args, failure=None):
        if failure:
            name, body = failure
            self.put('bin/' + name, '#!/usr/bin/env bash\n' + body + '\n')
            (self.bin / name).chmod(0o755)
        env = dict(os.environ, TMPDIR=self.tmp.as_posix())
        # Set PATH in Bash so Windows path separators cannot alter the test shim.
        command = 'export PATH="$PWD/bin:$PATH"; exec bash .tools/extract-locale-keys.sh "$@"'
        result = subprocess.run([BASH, '-c', command, 'fixture', *args], cwd=self.root,
                                env=env, capture_output=True, text=True)
        self.assertEqual(list(self.tmp.iterdir()), [], 'Temporary output leaked')
        return result

    def generate(self):
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)

    def snapshot(self):
        return {p.relative_to(self.root).as_posix(): (p.read_bytes(), p.stat().st_mtime_ns)
                for p in self.root.rglob('*') if p.is_file() and 'bin' not in p.relative_to(self.root).parts}

    def test_generation_preserves_format_and_exclusions(self):
        for name in ['Libs/A.lua', 'Mod/Libs/B.lua', 'EllesmereUILocales/C.lua',
                     '.release/D.lua', 'EllesmereUI_LocaleDev.lua', 'Upper.LUA']:
            self.put(name, 'EllesmereUI.L("Excluded")\n')
        self.generate()
        expected = ('# Auto-generated by .tools/extract-locale-keys.sh -- do not edit by hand.\n'
                    '# Canonical list of translatable English keys passed as string literals\n'
                    '# (2 unique). Regenerate after wrapping new strings. Keys passed as\n'
                    '# variables are not listed here -- use the in-game /euiloc harvester for\n'
                    '# the complete runtime set.\nApple\nZebra\n')
        self.assertEqual(self.output.read_bytes(), expected.encode())

    def test_current_check_preserves_bytes_timestamps_and_git_index(self):
        self.generate()
        git = shutil.which('git')
        self.assertIsNotNone(git, 'Git is required for the index preservation test')
        for args in [('init', '-q'), ('add', '.')]:
            subprocess.run([git, *args], cwd=self.root, capture_output=True, check=True)
        self.put('Core.lua', 'EllesmereUI.L("Apple")\nEllesmereUI.L("Zebra")\n-- unstaged\n')
        before = self.snapshot()
        result = self.run_script('--check')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_stale_check_does_not_write(self):
        self.generate()
        self.put('Core.lua', 'EllesmereUI.L("Changed")\n')
        before = self.snapshot()
        result = self.run_script('--check')
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn('out of date', result.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_crlf_checkout_is_current_without_rewriting(self):
        self.generate()
        self.output.write_bytes(self.output.read_bytes().replace(b'\n', b'\r\n'))
        before = self.snapshot()
        result = self.run_script('--check')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_zero_keys_is_valid(self):
        self.put('Core.lua', '-- no translation keys\n')
        self.generate()
        self.assertIn(b'(0 unique)', self.output.read_bytes())
        self.assertEqual(self.run_script('--check').returncode, 0)

    def test_missing_output_is_inconclusive(self):
        result = self.run_script('--check')
        self.assertEqual(result.returncode, 2)
        self.assertIn('Cannot read', result.stderr)
        self.assertFalse(self.output.exists())

    def test_grep_error_is_not_no_matches_and_preserves_output(self):
        self.generate()
        before = self.snapshot()
        result = self.run_script('--check', failure=('grep', 'echo injected read failure >&2; exit 2'))
        self.assertEqual(result.returncode, 2)
        self.assertIn('grep exit 2', result.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_pipeline_failure_cleans_temporaries(self):
        self.generate()
        before = self.snapshot()
        result = self.run_script('--check', failure=('sort', 'exit 2'))
        self.assertEqual(result.returncode, 2)
        self.assertEqual(self.snapshot(), before)

    def test_compare_error_is_inconclusive(self):
        self.generate()
        before = self.snapshot()
        result = self.run_script('--check', failure=('cmp', 'exit 2'))
        self.assertEqual(result.returncode, 2)
        self.assertIn('cmp exit 2', result.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_invalid_arguments_do_not_write(self):
        for args in [('--invalid',), ('--check', 'extra')]:
            with self.subTest(args=args):
                self.assertEqual(self.run_script(*args).returncode, 2)
                self.assertFalse(self.output.exists())


if __name__ == '__main__':
    unittest.main()
