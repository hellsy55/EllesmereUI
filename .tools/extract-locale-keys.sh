#!/usr/bin/env bash
#
# extract-locale-keys.sh
# Extracts every translatable key (the first string literal passed to
# EllesmereUI.L(...) or EllesmereUI.Lf(...)) from the addon source and writes a
# sorted, de-duplicated list to EllesmereUILocales/_keys.txt.
#
# This is the STATIC key list (literals only). Keys passed as variables -- e.g.
# L(cfg.text) -- cannot be seen statically; use the in-game /euiloc harvester for
# the complete runtime set. Together they cover everything.
#
# Usage: bash .tools/extract-locale-keys.sh [--check] (run from anywhere)
# CI uses this to verify EllesmereUILocales/_keys.txt is current (see locale-check.yml).
#
set -Eeuo pipefail
trap 'echo "Locale extraction or I/O failed; validation is inconclusive." >&2; exit 2' ERR
export LC_ALL=C

MODE=generate
if [ "$#" -eq 1 ] && [ "$1" = '--check' ]; then
  MODE=check
elif [ "$#" -ne 0 ]; then
  echo 'Usage: extract-locale-keys.sh [--check]' >&2
  exit 2
fi

# cd to the addon root (parent of .tools/)
cd "$(dirname "$0")/.."

OUT="EllesmereUILocales/_keys.txt"
TMP="$(mktemp -d)"
trap 'rm -rf -- "$TMP"' EXIT
trap 'exit 2' HUP INT TERM

# grep exit 1 means no matches; exit >1 is an extraction failure.
status=0
grep -rhoE 'EllesmereUI\.Lf?\("[^"]*"' \
  --include='*.lua' \
  --exclude-dir='Libs' \
  --exclude-dir='EllesmereUILocales' \
  --exclude-dir='.release' \
  --exclude='EllesmereUI_LocaleDev.lua' \
  . > "$TMP/matches" || status=$?
if [ "$status" -gt 1 ]; then
  echo "Locale extraction failed (grep exit $status)." >&2
  exit 2
fi
sed -E 's/^EllesmereUI\.Lf?\("//; s/"$//' "$TMP/matches" \
  | sort -u > "$TMP/keys"

COUNT="$(wc -l < "$TMP/keys" | tr -d ' ')"

{
  echo "# Auto-generated by .tools/extract-locale-keys.sh -- do not edit by hand."
  echo "# Canonical list of translatable English keys passed as string literals"
  echo "# ($COUNT unique). Regenerate after wrapping new strings. Keys passed as"
  echo "# variables are not listed here -- use the in-game /euiloc harvester for"
  echo "# the complete runtime set."
  cat "$TMP/keys"
} > "$TMP/expected"

if [ "$MODE" = check ]; then
  if [ ! -f "$OUT" ] || [ ! -r "$OUT" ]; then
    echo "Cannot read $OUT; validation is inconclusive." >&2
    exit 2
  fi
  # Git for Windows may materialize the committed LF text as CRLF.
  sed 's/\r$//' "$OUT" > "$TMP/current"
  status=0
  cmp -s -- "$TMP/expected" "$TMP/current" || status=$?
  if [ "$status" -eq 1 ]; then
    echo "$OUT is out of date. Run bash .tools/extract-locale-keys.sh and review the result." >&2
    exit 1
  elif [ "$status" -ne 0 ]; then
    echo "Cannot compare $OUT (cmp exit $status); validation is inconclusive." >&2
    exit 2
  fi
  echo "$OUT is current ($COUNT keys)."
else
  cat "$TMP/expected" > "$OUT"
  echo "Wrote $COUNT keys to $OUT"
fi
